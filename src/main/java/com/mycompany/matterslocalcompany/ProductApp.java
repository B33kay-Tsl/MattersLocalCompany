    private void jProccesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProccesActionPerformed
        // TODO add your handling code here: 
        
        //Declarations
        String locationName = jComboBoxLocation.getSelectedItem().toString();
        String Name = txtName.getText();
        double price = Double.parseDouble(txtPrice.getText());
        double vat = 0.15;
        double comm = 0.05;
        
        //get vat calculated
        double vatPrice = price * vat; 
        double commissionAmount = price * comm;
        
        //total sale  Amoun calculated
        double totalSaleAmount = price + vatPrice + commissionAmount;
        
        JOptionPane.showMessageDialog(this,
                    "\nCustomer Name: " + Name 
                   + "\nProduct: "+locationName 
                   +"\nVAT: R" + vatPrice
                   +"\nCOMMISSION: R" + commissionAmount
                   +"\nTOTAL: R" + totalSaleAmount );
        
        try
        {
            FileWriter writer = new FileWriter("data.txt");
            writer.write( "DATA LOG"
                   +"\n****************************"
                   + "\nCustomer Name: " + Name 
                   + "\nProduct: "+locationName 
                   +"\nVAT: R" + vatPrice
                   +"\nCOMMISSION: R" + commissionAmount
                   +"\nTOTAL: R" + totalSaleAmount 
                   +"\n**************************");
            writer.close();
            
            JOptionPane.showMessageDialog(this,
                    "Save Successfully");
            
        }catch(IOException e)
        {
             JOptionPane.showMessageDialog(this,
                    "Error, Saving into report" + e.getMessage());
            
        }
    
    }//GEN-LAST:event_jProccesActionPerformed

